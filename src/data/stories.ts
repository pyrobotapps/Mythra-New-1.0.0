export function filterStories(
  query: string,
  relationship: string,
  format: string,
  genre: string,
) {
  return stories.filter(
    (s) =>
      `${s.title} ${s.author} ${s.genre}`
        .toLowerCase()
        .includes(query.trim().toLowerCase()) &&
      (relationship === "All" || s.relationship === relationship) &&
      (format === "All" || s.format === format) &&
      (genre === "All" || s.genre === genre),
  );
}
